package dev.n2k02.morpheautomirror

import android.app.Presentation
import android.content.Context
import android.graphics.Color
import android.hardware.display.DisplayManager
import android.hardware.display.VirtualDisplay
import org.mozilla.geckoview.GeckoRuntime
import org.mozilla.geckoview.GeckoSession
import org.mozilla.geckoview.GeckoSessionSettings
import org.mozilla.geckoview.GeckoView

/**
 * Experimental browser-based renderer. A GeckoView in a Presentation is composited
 * onto the virtual display, whose output Surface belongs to Android Auto.
 *
 * Gecko does NOT acquire screen capture permissions or bypass secure video content.
 * All URLs are generated by FrameCaptureServer and restricted to loopback.
 */
internal class GeckoViewMirror(
    private val context: Context,
    private val port: Int,
    private val token: String,
) : AutoCloseable {
    private val displays = context.getSystemService(Context.DISPLAY_SERVICE) as DisplayManager
    private var display: VirtualDisplay? = null
    private var presentation: Presentation? = null
    private var browser: GeckoView? = null
    private var session: GeckoSession? = null

    fun attach(target: CarTarget) {
        detach()
        val virtualDisplay = displays.createVirtualDisplay(
            "morphe-car-geckoview",
            target.width, target.height, target.dpi, target.surface,
            DisplayManager.VIRTUAL_DISPLAY_FLAG_PRESENTATION
        )
        display = virtualDisplay
        try {
            val dialog = Presentation(context, virtualDisplay.display)
            val view = GeckoView(dialog.context).apply {
                // A TextureView composes into the virtual display. The default
                // SurfaceView may render in a separate layer on some hosts.
                setViewBackend(GeckoView.BACKEND_TEXTURE_VIEW)
                setBackgroundColor(Color.BLACK)
            }
            val geckoSession = GeckoSession(
                GeckoSessionSettings.Builder()
                    .usePrivateMode(true)
                    .allowJavascript(false)
                    .build()
            )
            geckoSession.setContentDelegate(object : GeckoSession.ContentDelegate {})
            geckoSession.open(runtime(context))
            view.setSession(geckoSession)
            browser = view
            session = geckoSession
            dialog.setContentView(view)
            dialog.show()
            presentation = dialog
            // Serve the document from the same origin as its image stream:
            // Firefox's security policy can then use 'self' rather than
            // allowing remote sites or cross-origin content.
            geckoSession.loadUri("http://127.0.0.1:$port/viewer?token=$token")
        } catch (e: Exception) {
            detach()
            throw e
        }
    }

    fun detach() {
        browser?.releaseSession()
        session?.close()
        session = null
        browser = null
        presentation?.dismiss()
        presentation = null
        display?.release()
        display = null
    }

    override fun close() = detach()

    private companion object {
        @Volatile private var sharedRuntime: GeckoRuntime? = null

        // Mozilla requires one GeckoRuntime per application process.
        fun runtime(context: Context): GeckoRuntime =
            sharedRuntime ?: synchronized(this) {
                sharedRuntime ?: GeckoRuntime.create(context.applicationContext).also {
                    sharedRuntime = it
                }
            }
    }
}
